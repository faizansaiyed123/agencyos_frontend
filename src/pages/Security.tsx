import { useState, type FormEvent } from "react";
import { useQuery, useQueryClient } from "@tanstack/react-query";
import { api } from "../api/client";
import type { MfaEnroll, MfaStatus } from "../api/types";
import { useAuth } from "../auth/AuthContext";
import { ErrorNote, Field, FormModal, PageHead, Spinner } from "../components/ui";
import { fmtDate } from "../lib";

export default function Security() {
  const { user, reload } = useAuth();
  const qc = useQueryClient();
  const status = useQuery({ queryKey: ["mfa-status"], queryFn: () => api<MfaStatus>("/auth/mfa/status") });
  const [enroll, setEnroll] = useState<MfaEnroll | null>(null);
  const [code, setCode] = useState("");
  const [recovery, setRecovery] = useState<string[] | null>(null);
  const [err, setErr] = useState<unknown>(null);
  const [busy, setBusy] = useState(false);
  const [disabling, setDisabling] = useState(false);
  const [pw, setPw] = useState(""); const [offCode, setOffCode] = useState("");

  const run = async (fn: () => Promise<void>) => { setBusy(true); setErr(null); try { await fn(); } catch (e) { setErr(e); } finally { setBusy(false); } };
  const refresh = async () => { await qc.invalidateQueries({ queryKey: ["mfa-status"] }); await reload(); };
  const start = () => run(async () => setEnroll(await api<MfaEnroll>("/auth/mfa/enroll", { method: "POST" })));
  const confirm = (e: FormEvent) => { e.preventDefault(); run(async () => {
    const r = await api<{ recovery_codes: string[] }>("/auth/mfa/enroll/confirm", { body: { code } });
    setRecovery(r.recovery_codes); setEnroll(null); setCode(""); await refresh();
  }); };

  if (status.isLoading) return <Spinner />;
  const s = status.data;
  return (
    <>
      <PageHead title="Security" sub={user?.email} />
      <ErrorNote error={status.error ?? err} />
      <div className="panel" style={{ maxWidth: 640 }}>
        <header><h3>Two-factor authentication</h3>{s?.mfa_enabled ? <span className="badge moss">On</span> : <span className="badge">Off</span>}</header>
        <div className="body">
          {recovery && (
            <div style={{ marginBottom: 18 }}>
              <div className="notice">Save these recovery codes now. Each works once, and they won't be shown again.</div>
              <div className="codes">{recovery.map((c) => <span key={c}>{c}</span>)}</div>
              <button className="btn ghost sm" style={{ marginTop: 10 }} onClick={() => setRecovery(null)}>I've saved them</button>
            </div>
          )}
          {s?.mfa_enabled ? (
            <>
              <p style={{ marginTop: 0 }}>Enabled {fmtDate(s.enrolled_at)}. {s.recovery_codes_remaining} recovery {s.recovery_codes_remaining === 1 ? "code" : "codes"} left.</p>
              <button className="btn danger" onClick={() => setDisabling(true)}>Turn off two-factor</button>
            </>
          ) : enroll ? (
            <form onSubmit={confirm}>
              <p style={{ marginTop: 0 }}>Scan this with an authenticator app, then enter the 6-digit code it shows.</p>
              {/* SVG is generated by our own API (server-side qrcode), not user input. */}
              <div className="qr" aria-label="QR code" dangerouslySetInnerHTML={{ __html: enroll.qr_code_svg }} />
              <p className="muted">Can't scan? Enter this key manually: <code className="secret">{enroll.secret}</code></p>
              <Field label="6-digit code"><input value={code} onChange={(e) => setCode(e.target.value)} inputMode="numeric" pattern="\d{6}" maxLength={6} required autoComplete="one-time-code" /></Field>
              <button className="btn primary" disabled={busy}>Confirm and turn on</button>{" "}
              <button type="button" className="btn ghost" onClick={() => setEnroll(null)}>Cancel</button>
            </form>
          ) : (
            <>
              <p style={{ marginTop: 0 }}>Require a code from an authenticator app when you sign in.</p>
              <button className="btn primary" disabled={busy} onClick={start}>Set up two-factor</button>
            </>
          )}
        </div>
      </div>
      {disabling && (
        <FormModal title="Turn off two-factor" submitLabel="Turn off" danger onClose={() => { setDisabling(false); setPw(""); setOffCode(""); }}
          onSubmit={async () => { await api("/auth/mfa/disable", { body: { password: pw, code: offCode } }); await refresh(); }}>
          <Field label="Password"><input type="password" value={pw} onChange={(e) => setPw(e.target.value)} required autoFocus autoComplete="current-password" /></Field>
          <Field label="Authenticator or recovery code"><input value={offCode} onChange={(e) => setOffCode(e.target.value)} required minLength={6} maxLength={9} /></Field>
        </FormModal>
      )}
    </>
  );
}
